"""Original-PDF pixel context for producer-owned unresolved G17 candidate groups.

A readable render is NOT opening existence, physical wall identity or metric
authority. The original PDF is byte-verified by the caller's SHA gate. Each
raw candidate bbox is independently regenerated by current source producer;
nothing in this script chooses a host, removes a candidate or predicts a count.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
from hashlib import sha256
import json
from pathlib import Path
import math

import fitz

from pb_live_physical_net_wall_integration import LIVE_PHYSICAL_NET_WALL_INTEGRATION_SCHEMA_VERSION
from pb_live_physical_opening_void_composition import compose_live_physical_opening_voids
from pb_live_wall_opening_authority_composition import compose_live_wall_opening_authority
from pb_migration_contracts import EvidenceResolutionStatus
from pb_source_observation_authority import ObservationSelector
from pb_source_visibility_authority import SourceVisibilityProducer
from tools.diag_gptmax_producer_owned_g17_wall_shadow import _retention


def original_raw_g17_context_report(source_bytes: bytes, *, page_id: str, output_dir: Path, padding_pt: float = 25.):
    if (not page_id.isdecimal() or int(page_id) <= 0 or str(int(page_id)) != page_id
            or not math.isfinite(padding_pt) or not 0. <= padding_pt <= 100.):
        raise ValueError('original page address and bounded diagnostic padding required')
    digest=sha256(source_bytes).hexdigest()
    source=SourceVisibilityProducer(producer_method='live-physical-net-wall',
        producer_version=LIVE_PHYSICAL_NET_WALL_INTEGRATION_SCHEMA_VERSION)
    pub=source.ingest_native_pdf_bytes(document_id=f'live-source:{digest[:32]}',
        source_bytes=source_bytes,source_locator='memory://original-raw-g17-source-review.pdf')
    revision_id=pub.revision.revision_id

    def compose():
        composition=compose_live_wall_opening_authority(
            source_visibility_producer=source,revision_id=revision_id,page_ids=(page_id,))
        voids=compose_live_physical_opening_voids(
            source_visibility_producer=source,wall_opening_composition=composition)
        return composition,voids

    composition,voids=compose()
    pub=source.published_snapshot_for_revision(revision_id)
    if pub is None or pub.revision.source_sha256!=digest:
        raise RuntimeError('original source producer verification unavailable')
    baseline=_retention(composition,voids,verify_customer_rows=True)
    physical=composition.physical_opening_authority
    all_g17=pub.raster_opening_primitive_observation_ids
    visibility=source.authority()
    candidates=[]
    selectors_by_source_id={}
    for oid in all_g17:
        selector=ObservationSelector(pub.revision.document_id,revision_id,digest,
            pub.snapshot.snapshot_id,oid)
        proof=visibility.resolve_raster_opening_primitive(selector)
        if (proof.status is not EvidenceResolutionStatus.CORROBORATED
                or proof.observation is None):
            raise RuntimeError('original G17 complete source inventory failed')
        if proof.observation.page_id == page_id:
            candidates.append(selector)
            selectors_by_source_id[oid]=selector
    if not candidates:
        raise RuntimeError('requested original source page has no G17 observation')
    groups=physical.audited_unresolved_source_candidate_groups(candidates[0],family='raster')
    closure=physical.assess_raster_candidate_closure(candidates[0])
    if (closure.status is not EvidenceResolutionStatus.CORROBORATED
            or closure.candidate_universe_complete
            or len(groups)!=len(closure.unresolved_candidate_ids)
            or {row['candidate_id'] for row in groups}!=set(closure.unresolved_candidate_ids)):
        raise RuntimeError('original raw candidate per-source closure changed')
    with fitz.open(stream=source_bytes,filetype='pdf') as pdf:
        if int(page_id)>len(pdf):
            raise RuntimeError('original PDF page out of range')
        page=pdf[int(page_id)-1]
        bbox=page.rect
        output_dir.mkdir(parents=True,exist_ok=True)
        rows=[]
        for index,group in enumerate(sorted(groups,key=lambda row:row['candidate_id'])):
            # Independently ask the real current producer about *each* exact
            # original member. A source member may belong to another already
            # proven opening; that NEVER resolves this raw candidate group.
            member_existence=[]
            for observation_id in group['source_observation_ids']:
                address=selectors_by_source_id.get(observation_id)
                if address is None:
                    raise RuntimeError('original raw gap source member outside selected page')
                proof=physical.prove_existence(address)
                member_existence.append(dict(
                    observation_id=observation_id,
                    source_existence_status=proof.status.value,
                    source_existence_reason_codes=list(proof.reason_codes),
                    independently_proven_opening_id=(
                        proof.existence_record.record_id if proof.existence_record is not None else None),
                    candidate_id=(proof.candidate.candidate_id if proof.candidate is not None else None),
                    raw_group_to_opening_identity_granted=False))
            coords=group['aperture_bbox_pt']
            if (not isinstance(coords,list) or len(coords)!=4
                    or not all(type(x) in (float,int) and math.isfinite(x) for x in coords)):
                raise RuntimeError('source-authenticated original gap bbox unavailable')
            gap=fitz.Rect(coords)
            if (gap.is_empty or gap.is_infinite or not bbox.contains(gap)):
                raise RuntimeError('source aperture is outside original PDF page')
            crop=fitz.Rect(max(bbox.x0,gap.x0-padding_pt),
                           max(bbox.y0,gap.y0-padding_pt),
                           min(bbox.x1,gap.x1+padding_pt),
                           min(bbox.y1,gap.y1+padding_pt))
            if crop.is_empty or crop.is_infinite:
                raise RuntimeError('original visual context crop unavailable')
            pixmap=page.get_pixmap(matrix=fitz.Matrix(3.,3.),clip=crop,alpha=False)
            png=pixmap.tobytes('png')
            name=f'raw-source-candidate-{index+1:02d}.png'
            (output_dir/name).write_bytes(png)
            rows.append(dict(raw_candidate_id=group['candidate_id'],
                source_observation_ids=group['source_observation_ids'],
                actual_producer_member_existence_decisions=member_existence,
                source_raw_aperture_bbox_pt=coords,
                displayed_context_pdf_bbox_pt=[crop.x0,crop.y0,crop.x1,crop.y1],
                context_png_name=name,context_png_sha256=sha256(png).hexdigest(),
                source_semantics_unproved=True,opening_existence_granted=False,
                physical_wall_equivalence_granted=False,host_granted=False,
                metric_quantity_granted=False))
    recomp,revoids=compose()
    candidate=_retention(recomp,revoids,verify_customer_rows=True)
    if baseline!=candidate or source.published_snapshot_for_revision(revision_id)!=pub:
        raise RuntimeError('original production signed customer receipts or source snapshot changed')
    return dict(source_sha256=digest,revision_id=revision_id,snapshot_id=pub.snapshot.snapshot_id,
        page_id=page_id,original_raw_candidate_count=closure.raw_candidate_count,
        original_raw_resolved_count=closure.resolved_candidate_count,
        unresolved_raw_groups=rows,source_candidate_universe_complete=False,
        original_customer_receipts_unchanged=True,
        unchanged_signed_customer_quantity_count=baseline['customer_verification']['valid_quantity_count'],
        source_PDF_render_is_diagnostic_only=True,
        source_observation_and_aperture_authority_not_promoted=True,
        physical_wall_host_count_quantity_granted=False)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--pdf',type=Path,required=True)
    p.add_argument('--page-id',required=True)
    p.add_argument('--output-dir',type=Path,required=True)
    a=p.parse_args()
    report=original_raw_g17_context_report(a.pdf.read_bytes(),page_id=a.page_id,
        output_dir=a.output_dir)
    (a.output_dir/'manifest.json').write_text(json.dumps(report,sort_keys=True,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items() if k not in ('unresolved_raw_groups',)},
        sort_keys=True))


if __name__=='__main__':
    main()
