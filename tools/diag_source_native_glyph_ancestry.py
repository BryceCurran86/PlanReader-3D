"""Read-only census of original PDF word/glyph ancestry for a material code.

No raster OCR, Unicode correction, material-definition authentication, or
commercial evidence is generated by this tool. All competing native blocks
are retained, including blocks whose text profiles disagree.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from collections import defaultdict
from pathlib import Path

import fitz


def _rect(value):
    if not isinstance(value, (tuple, list)) or len(value) != 4:
        return None
    try:
        result = tuple(float(v) for v in value)
    except (ValueError, TypeError):
        return None
    if not all(math.isfinite(v) for v in result):
        return None
    if not (result[0] < result[2] and result[1] < result[3]):
        return None
    return result


def _origin_in_box(origin, box):
    if not isinstance(origin, (tuple, list)) or len(origin) != 2:
        return False
    x, y = float(origin[0]), float(origin[1])
    return all(math.isfinite(v) for v in (x, y)) and (
        box[0] - 1e-3 <= x <= box[2] + 1e-3
        and box[1] - 1e-3 <= y <= box[3] + 1e-3
    )


def _native_char_lines(page, flags):
    """Retain every original char, font and address; no profile wins by rank."""
    raw = page.get_text("rawdict", flags=flags)
    lines = []
    for block_i, block in enumerate(raw.get("blocks", ())):
        for line_i, line in enumerate(block.get("lines", ())):
            chars = []
            for span_i, span in enumerate(line.get("spans", ())):
                for char_i, char in enumerate(span.get("chars", ())):
                    token, origin, bbox = (
                        char.get("c"), char.get("origin"), _rect(char.get("bbox"))
                    )
                    if not isinstance(token, str) or len(token) != 1:
                        continue
                    if bbox is None or not _origin_in_box(origin, bbox):
                        # Glyph ink can protrude beyond its origin box, but
                        # malformed origins never become trusted evidence.
                        pass
                    chars.append({
                        "character": token,
                        "unicode": ord(token),
                        "origin": tuple(origin) if isinstance(origin, (tuple, list)) else None,
                        "glyph_bbox": bbox,
                        "font": span.get("font"),
                        "source_address": (block_i, line_i, span_i, char_i),
                    })
            if chars:
                lines.append(tuple(chars))
    return tuple(lines)


def _exact_runs(lines, text, bbox):
    """Report all exact contiguous native-character origins, never elect one."""
    matches = []
    if not text:
        return matches
    for line in lines:
        if len(line) < len(text):
            continue
        for start in range(len(line) - len(text) + 1):
            window = line[start:start + len(text)]
            if "".join(c["character"] for c in window) != text:
                continue
            if not all(_origin_in_box(c["origin"], bbox) for c in window):
                continue
            matches.append({
                "unicode_codepoints": [c["unicode"] for c in window],
                "source_addresses": [c["source_address"] for c in window],
                "fonts": [c["font"] for c in window],
                "glyph_boxes": [c["glyph_bbox"] for c in window],
            })
    return matches


def _trace_matches(page, text, bbox):
    """Independent original PDF texttrace, including font glyph IDs and paint."""
    candidates = []
    for span in page.get_texttrace():
        seqno = span.get("seqno")
        font = span.get("font")
        paint_type = span.get("type")
        opacity = span.get("opacity")
        chars = span.get("chars", ())
        if len(chars) < len(text):
            continue
        for start in range(len(chars) - len(text) + 1):
            window = chars[start:start + len(text)]
            if any(not isinstance(c[0], int) or c[0] < 0 or c[0] > 0x10FFFF for c in window):
                continue
            if "".join(chr(c[0]) for c in window) != text:
                continue
            if not all(_origin_in_box(c[2], bbox) for c in window):
                continue
            candidates.append({
                "font": font,
                "sequence_number": seqno,
                "paint_type": paint_type,
                "opacity": opacity,
                "unicode_codepoints": [c[0] for c in window],
                "glyph_ids": [c[1] for c in window],
                "origins": [tuple(c[2]) for c in window],
                "glyph_boxes": [_rect(c[3]) for c in window],
            })
    return candidates


def inspect_original_glyphs(
    source_bytes: bytes, *, expected_sha256: str, page_number: int, code: str
) -> dict:
    if type(source_bytes) is not bytes:
        raise TypeError("immutable PDF bytes required")
    digest = hashlib.sha256(source_bytes).hexdigest()
    if type(expected_sha256) is not str or digest != expected_sha256:
        raise ValueError("original source SHA mismatch")
    if type(page_number) is not int or page_number < 1:
        raise ValueError("positive native source page required")
    if type(code) is not str or not code or code.strip() != code:
        raise ValueError("exact native material code required")
    with fitz.open(stream=source_bytes, filetype="pdf") as document:
        if page_number > len(document):
            raise ValueError("source page out of bounds")
        page = document[page_number - 1]
        words_by_block = defaultdict(list)
        for word in page.get_text("words", flags=fitz.TEXTFLAGS_WORDS):
            if len(word) < 8:
                continue
            box = _rect(word[:4])
            if box is None:
                continue
            token = str(word[4])
            words_by_block[int(word[5])].append({
                "text": token,
                "bbox": box,
                "native_source_address": (int(word[5]), int(word[6]), int(word[7])),
            })
        profiles = {
            "textflags_words": _native_char_lines(page, fitz.TEXTFLAGS_WORDS),
            "default_rawdict": _native_char_lines(page, 0),
        }
        blocks = []
        for block_id, words in sorted(words_by_block.items()):
            if not any(word["text"] == code for word in words):
                continue
            results = []
            for word in sorted(words, key=lambda w: w["native_source_address"]):
                origin_proofs = {
                    name: _exact_runs(lines, word["text"], word["bbox"])
                    for name, lines in profiles.items()
                }
                trace = _trace_matches(page, word["text"], word["bbox"])
                results.append({
                    **word,
                    "literal_codepoints": [ord(c) for c in word["text"]],
                    "rawdict_profile_exact_run_counts": {
                        key: len(value) for key, value in origin_proofs.items()
                    },
                    "rawdict_profile_original_runs": origin_proofs,
                    "original_texttrace_matches": trace,
                    "original_texttrace_match_count": len(trace),
                    "independent_raster_literal_proven": False,
                })
            blocks.append({"native_block_no": block_id, "words": results})
    return {
        "source_sha256": digest,
        "page_number": page_number,
        "exact_requested_code": code,
        "candidate_blocks": blocks,
        "candidate_block_count": len(blocks),
        "source_profile_comparison_only": True,
        "independent_raster_literal_proven": False,
        "material_definition_authenticated": False,
        "source_finish_occurrence_authenticated": False,
        "physical_floor_ownership_authenticated": False,
        "commercial_quantity_published": False,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pdf", type=Path, required=True)
    parser.add_argument("--source-sha", required=True)
    parser.add_argument("--page", type=int, required=True)
    parser.add_argument("--code", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    report = inspect_original_glyphs(
        args.pdf.read_bytes(),
        expected_sha256=args.source_sha,
        page_number=args.page,
        code=args.code,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2))
    print(json.dumps({
        "source_sha256": report["source_sha256"],
        "candidate_blocks": report["candidate_block_count"],
        "candidate_block_word_counts": [
            len(block["words"]) for block in report["candidate_blocks"]
        ],
        "unproved_native_words": [
            {"block": block["native_block_no"],
             "original_source_addresses": [
                word["native_source_address"]
                for word in block["words"]
                if word["original_texttrace_match_count"] != 1
                or any(n != 1 for n in word["rawdict_profile_exact_run_counts"].values())
            ]}
            for block in report["candidate_blocks"]
        ],
        "commercial_quantity_published": False,
    }, sort_keys=True))


if __name__ == "__main__":
    main()
